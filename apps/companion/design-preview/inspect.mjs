import { chromium } from 'playwright';
import { readFile, mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { checkSidebar } from './sidebar-check.mjs';
const output = process.argv[2] ?? '/tmp/focus-queue-screenshots';
await mkdir(output,{recursive:true});
const readUrl = async file => JSON.parse((await readFile(file,'utf8')).split('\n').find(line=>line.startsWith('{"url"'))).url;
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.goto(await readUrl('/tmp/focus-integrated-preview.log'));
const nav = page.getByRole('navigation',{name:'Workspace sections'});
await nav.getByRole('button',{name:'Jobs',exact:true}).click();
await page.getByRole('button',{name:'New job',exact:true}).waitFor();
await checkSidebar(page,output);
assert.equal(await page.locator(':root').evaluate(node=>getComputedStyle(node).getPropertyValue('--selection-accent').trim()),'#0096ff');
assert.equal(await page.locator(':root').evaluate(node=>getComputedStyle(node).getPropertyValue('--green').trim()),'#0000ff');
for(const label of ['Jobs','Overview','Needs Attention','Facts','Resumes','Answers','Consent defaults','Automation','Accounts & Sign-in','Settings','Trash']) {
  await nav.getByRole('button',{name:label,exact:true}).click();
  await page.waitForTimeout(500);
  await page.screenshot({path:`${output}/${label.toLowerCase().replaceAll(' ','-')}.png`,fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${label} desktop overflow`);
}
await nav.getByRole('button',{name:'Needs Attention',exact:true}).click();
await page.locator('.focus-item').first().waitFor();
await page.locator('.focus-item').nth(1).focus();
await page.keyboard.press('Enter');
assert.equal(await page.locator('.focus-item[aria-pressed=true]').count(),1);
await page.getByRole('button',{name:/Open job /}).click();
await page.locator('dialog.job-drawer').waitFor();
await page.getByRole('button',{name:'Close job details',exact:true}).click();
await nav.getByRole('button',{name:'Needs Attention',exact:true}).click();
await page.getByLabel('Filter by reason').selectOption('expired_agent_attempt');
await page.getByText('No jobs match this reason filter.',{exact:true}).waitFor();
await page.getByRole('button',{name:'Clear filter',exact:true}).click();
await page.route('**/api/attention',route=>route.fulfill({status:503,body:'{}'}));
await page.getByRole('button',{name:'Refresh attention',exact:true}).click();
await page.locator('.attention-panel [role=alert]').waitFor();
await page.screenshot({path:`${output}/attention-error.png`,fullPage:true});
await page.unroute('**/api/attention');
await page.getByRole('button',{name:'Refresh attention',exact:true}).click();
await page.locator('.attention-panel [role=alert]').waitFor({state:'hidden'});
await nav.getByRole('button',{name:'Resumes',exact:true}).click();
await page.getByRole('button',{name:'Resume extraction',exact:true}).click();
await page.locator('.extraction-proposal-button').first().click();
await page.locator('.extraction-review').waitFor();
await page.screenshot({path:`${output}/extraction-review.png`,fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:`${output}/extraction-review-mobile.png`,fullPage:true});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'extraction mobile overflow');
for(const label of ['Needs Attention','Jobs','Facts','Resumes','Answers','Consent defaults','Automation','Accounts & Sign-in','Settings','Trash']) {
  await nav.getByRole('button',{name:label,exact:true}).click();
  await page.waitForTimeout(300);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${label} mobile overflow`);
  await page.screenshot({path:`${output}/${label.toLowerCase().replaceAll(' ','-')}-mobile.png`,fullPage:true});
}
await page.goto(await readUrl('/tmp/focus-integrated-empty.log'));
await nav.getByRole('button',{name:'Needs Attention',exact:true}).click();
await page.getByText('Nothing needs your attention.',{exact:true}).waitFor();
await page.screenshot({path:`${output}/empty-mobile.png`});
assert.deepEqual(errors,[]);
console.log('Desktop/mobile sections, queue selection, job handoff, empty state: passed.');
await browser.close();
